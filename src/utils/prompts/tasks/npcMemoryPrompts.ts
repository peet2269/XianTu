/**
 * NPC 记忆总结提示词：把某个 NPC 的若干条记忆压缩成一段第一人称总结
 */
export function buildNpcMemorySummaryPrompts(npcName: string, memoriesText: string, saveDataJson: string) {
  const system = `你是「${npcName}」的记忆整理者。这是纯文本总结任务：不是游戏对话，不推进剧情，不写角色台词。

## 要求
- 以${npcName}的第一人称"我"叙述，按时间顺序，150-250字，连贯成段
- 保留：人名（尤其是主角的名字）、地名、事件、物品往来、关系与情感的变化
- 舍去：对话原文、细碎的情绪描写与过程细节
- 只依据用户给出的记忆内容，不添加原文没有的事；存档数据仅用于核对名称与背景

## 输出
只输出JSON，不要代码块、<thinking> 标签或其他文字：{"text":"总结内容"}

## 示例
原文："青云峰遇千夜。他帮我击退魔修。我很感激。他送我聚气丹。三天后藏经阁再遇。他求教剑法。我教他基础剑诀。"
✅ {"text":"我在青云峰遇到千夜，那时魔修来袭，多亏他出手我才脱险，心中十分感激，他还赠我一枚聚气丹。三日后我们在藏经阁重逢，他向我求教剑法，我便传了他基础剑诀。"}
❌ "我继续修炼，又遇到了新的机缘……"（编造了原文没有的内容）

## 游戏存档数据（仅供参考）
${saveDataJson}`;

  const user = `请总结以下属于「${npcName}」的记忆，严格依据原文，不要编造：

${memoriesText}`;

  return { system, user };
}
