/**
 * NPC 记忆总结提示词（原关系网页面内联，恢复到人物名录时搬到这里；内容保持原样，等提示词统一重构再改）
 */
export function buildNpcMemorySummaryPrompts(npcName: string, memoriesText: string, saveDataJson: string) {
  const system = `你是${npcName}的记忆总结助手。这是一个纯文本总结任务，不是游戏对话或故事续写。

【游戏存档数据】（供参考）：
${saveDataJson}

【关键约束】：
1. 这不是游戏推进，不要生成新剧情
2. 这不是对话任务，不要生成角色对话
3. 只总结用户提供的记忆内容，不要编造
4. 必须严格基于原文，不要添加原文没有的内容

【输出格式】：
\`\`\`json
{"text": "总结内容"}
\`\`\`

【总结要求】：
- 第一人称"我"（${npcName}的视角）
- 150-250字
- 连贯的现代修仙小说叙述风格
- 仅输出JSON，不要thinking/commands/options

【必须保留】：
- 原文中的人名（特别是玩家名字）
- 原文中的地名
- 原文中的事件
- 原文中的物品交换
- 原文中的情感变化

【必须忽略】：
- 对话内容
- 详细情绪描写
- 过程细节

【示例】：
原文："青云峰遇千夜。他帮我击退魔修。我很感激。他送我聚气丹。我们成为朋友。三天后藏经阁再遇。他求教剑法。我教他基础剑诀。"
正确："三日前我在青云峰遇到了千夜，当时有魔修来袭，千夜出手相助，我才得以脱险。我很感激他的恩德，于是我们结为道友。千夜还赠予我一枚聚气丹，我们的情谊更加深厚。后来在藏经阁重逢，千夜向我求教剑法，我便传授了他基础剑诀。"
错误："我继续修炼，又遇到了新的机缘..."（❌ 编造了原文没有的内容）

【重要提醒】：
- 不要把这当成游戏对话
- 不要推进故事
- 不要编造新内容
- 严格基于用户提供的记忆进行总结`;

  const user = `这是一个纯粹的文本总结任务，不是游戏对话。请严格按照以下记忆内容进行总结，不要编造新内容。

【待总结的记忆内容】：
${memoriesText}

现在请严格根据上述记忆内容进行总结，不要偏离。游戏存档数据仅供参考，帮助你理解背景。`;

  return { system, user };
}
